/* 2. Arithmetic Operators
    arithmetic operators are used to perform mathematical operations on numbers. The most common arithmetic operators are addition (+), subtraction (-), multiplication (*), division (/), and modulus (%).
*/


let a = 15; // Assigns the value 15 to the variable a
let b = 4; // Assigns the value 4 to the variable b 

let sum = a + b; // Adds a and b
console.log("Sum of a and b:", sum); // Output: Sum of a and b: 19  
let difference = a - b; // Subtracts b from a
console.log("Difference of a and b:", difference); // Output: Difference of a and b: 11
let product = a * b; // Multiplies a and b
console.log("Product of a and b:", product); // Output: Product of a and b: 60
let quotient = a / b; // Divides a by b     
console.log("Quotient of a and b:", quotient); // Output: Quotient of a and b: 3.75
let remainder = a % b; // Calculates the remainder of a divided by b
console.log("Remainder of a divided by b:", remainder); // Output: Remainder of a divided by b: 3       
let exponentiation = a ** b; // Raises a to the power of b
console.log("Exponentiation of a to the power of b:", exponentiation); // Output: Exponentiation of a to the power of b: 50625  
