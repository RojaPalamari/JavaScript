/* 1. Assignment Operators
    assignment operators are used to assign values to variables. The most common assignment operator is the equal sign (=), which assigns the value on the right to the variable on the left.
*/ 

let x = 10; // Assigns the value 10 to the variable x
console.log("Value of x:", x); // Output: Value of x: 10    

let y = 5; // Assigns the value 5 to the variable y
y = y + 2; // Adds 2 to the current value of y and assigns the result back to y
console.log("Value of y after addition:", y); // Output: Value of y after addition: 7

let z = 3; // Assigns the value 3 to the variable z
z *= 4; // Multiplies the current value of z by 4 and assigns the result back to z
console.log("Value of z after multiplication:", z); // Output: Value of z after multiplication: 12
