let x = 10;

switch(x){
    case 10:
        let b = "first case";
        console.log(b);
        break;
    case 10:
        let a = "Second case";
        console.log(a);
        break;
    default:
        console.log("default case");

}
//A switch executes from the first matching case and continues until break or the end of the switch.