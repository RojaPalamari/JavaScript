/* Naming Conventions */
// ======================

//1. camelCase: The first word is in lowercase, and the first letter of each subsequent word is capitalized.            
let firstName = "John";
console.log(firstName); // John

let lastName = "Doe";   
console.log(lastName); // Doe

//2. PascalCase: The first letter of each word is capitalized. This convention is often used for class names.
let UserProfile = "PascalCase";
console.log(UserProfile); // User Profile   

let Product = "Class name style";
console.log(Product); // Class name style

// 3. snake_case: All letters are in lowercase, and words are separated by underscores. 
let user_name = "snake_case";
console.log(user_name); // snake_case    

let product_price = 67.98;
console.log(product_price); // 67.98

// 4. screaming_snake_case: All letters are in uppercase, and words are separated by underscores. This convention is often used for constants.
const MAX_VALUE = 100;
console.log(MAX_VALUE); // 100  

const MIN_VALUE = 0;
console.log(MIN_VALUE); // 0    

const API_KEY = "abcd6543";
console.log(API_KEY); // abcd6543

//5. hangarian Notation: This convention involves prefixing variable names with a lowercase letter or letters that indicate the variable's type or purpose. For example, "str" for strings, "num" for numbers, "arr" for arrays, etc.
let strName = "Hungarian Notation";
console.log(strName); // Hungarian Notation

let numAge = 25;
console.log(numAge); // 25

let arrItems = [1, 2, 3];
console.log(arrItems); // [1, 2, 3] 
